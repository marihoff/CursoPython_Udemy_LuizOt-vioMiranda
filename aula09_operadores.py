adicao = 10 + 10
print('Adição', adicao)

subtracao = 10 - 5
print('Subtração', subtracao)

multiplicacao = 10 * 10
print('Multiplicação', multiplicacao)

divisao = 10 / 3  # sempre irá retornar em float
print('Divisão', divisao)

divisao_inteira = 10 // 3 #retorna sempre número inteiro, descartando a parte decimal
print('Divisão inteira', divisao_inteira)

exponenciacao = 2 ** 10
print('Exponenciação', exponenciacao)

modulo = 55 % 2  # resto da divisão
print('Módulo', modulo)

print(10 % 8 == 0) #sinal de divisão, se o resto da divisão for igual a 0, então o número é divisível pelo outro, se retorna outro valor diferente de 0, então o número não é divisível pelo outro, retornando False
