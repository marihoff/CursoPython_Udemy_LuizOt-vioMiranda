#Sobre a função print

print(12, 31, sep="-") #o sep é o separador, que por padrão é um espaço, mas pode ser alterado para qualquer coisa

#o sep será para separar os valores passados na função do print, no terminal ele sairá como 12-31 

#se clicar em cima da linha e fazer ctrl C ctrl V, ela copia o código para baixo
print(56, 78)

print(12, 31, sep="-", end="\r\n") #o end é o finalizador, que por padrão é uma quebra de linha, mas pode ser alterado para qualquer coisa

print(12, 31, sep="-", end="##") #o end será para finalizar a linha, no terminal ele sairá como 12-31##

